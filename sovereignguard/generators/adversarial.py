def scenario_max_score(batch: AttackBatch, feats: pd.DataFrame,
                       tx: pd.DataFrame, prob: np.ndarray) -> np.ndarray:
    """Per-scenario evasion score = max detector score across its events.

    Max, not mean: a campaign is caught if *any* of its events alerts, so the
    maximum is the quantity an attacker is actually trying to keep low.
    """
    df = pd.DataFrame({"attack_id": tx["attack_id"].to_numpy(), "p": prob})
    agg = df[df["attack_id"] != ""].groupby("attack_id")["p"].max()
    return batch.scenarios["attack_id"].map(agg).fillna(0.0).to_numpy()
