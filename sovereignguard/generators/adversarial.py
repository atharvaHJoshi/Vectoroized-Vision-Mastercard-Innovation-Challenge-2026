"""
Adversarial attack generation (Phase 17) — the adaptive half of the loop.

This is the module that turns a static benchmark into a lab. Instead of
generating attacks from a fixed difficulty preset, it reads a `GapReport` from
the deployed detector and mutates the Red Team's knobs *in the direction the
detector has been measured to be weak*.

The mapping from a diagnosed cause to a knob change is explicit and auditable —
`ADVERSARIAL_MOVES` below — rather than an opaque search. Each move is the
concrete behaviour a real attacker would adopt on learning that a control does
not fire, and each is annotated with the gap-analysis cause that justifies it.

Two generation modes:

  `adapt_knobs`  – deterministic, interpretable. Push the knobs implicated by
                   the top-lift causes. This is what the dashboard shows.

  `search`       – optional score-guided refinement. Generate candidate
                   variants, score them with the deployed detector, and keep the
                   ones that evade it. This is a black-box evasion search, and
                   it is the closest analogue to what an attacker with query
                   access to a decision endpoint would actually do.

IMPORTANT ON HONESTY OF THE LOOP
--------------------------------
`search` uses the detector to select attacks, so attacks it produces are
adversarially selected *against that specific model*. When they are later used
to retrain, the improvement must be measured on a FRESH batch generated by the
same process but never shown to the model — otherwise the reported gain is just
memorisation. `adversarial_loop` in pipeline.py enforces that.
"""
from __future__ import annotations

import dataclasses
from dataclasses import dataclass, field
from typing import Callable, Dict, List, Optional, Sequence, Tuple

import numpy as np
import pandas as pd

from .. import config as C
