@dataclass
class AdaptationPlan:
    """What the adversarial generator decided to do, and why."""
    base_difficulty: str
    intensity: float
    moves: List[Dict] = field(default_factory=list)
    target_segments: List[Dict] = field(default_factory=list)
    knobs_before: Dict = field(default_factory=dict)
    knobs_after: Dict = field(default_factory=dict)

    def to_dict(self) -> Dict:
        return dataclasses.asdict(self)

    def narrative(self) -> str:
        if not self.moves:
            return "No adaptation applied — no exploitable gap identified."
        parts = [f"Adapting from {self.base_difficulty} at intensity "
                 f"{self.intensity:.2f}. Diagnosed weaknesses and responses:"]
        for m in self.moves:
            parts.append(f"  - {m['cause_label']} (lift {m['lift']:.2f}x): {m['rationale']}")
        if self.target_segments:
            seg = ", ".join(f"{s['attack_type']}/{s['difficulty']} (recall {s['recall']:.0%})"
                            for s in self.target_segments[:3])
            parts.append(f"  Concentrating on weakest segments: {seg}.")
        return "\n".join(parts)


def _knobs_snapshot(k: Knobs) -> Dict:
    d = dataclasses.asdict(k)
    return {kk: (list(vv) if isinstance(vv, tuple) else vv) for kk, vv in d.items()}


def adapt_knobs(gap: GapReport, base_difficulty: str = "HARD",
                intensity: float = 0.85, max_moves: int = 4,
                min_lift: float = 1.05) -> Tuple[Knobs, AdaptationPlan]:
    """Turn a gap diagnosis into concrete Red Team parameters.

    Only causes that actually explain misses (positive excess AND lift above
    min_lift) are acted on, so a well-defended model produces few or no moves
    rather than random mutation.
    """
    base = KNOBS[base_difficulty]
    k = dataclasses.replace(base)
    k.label = "ADVERSARIAL"
    plan = AdaptationPlan(base_difficulty=base_difficulty, intensity=float(intensity),
                          knobs_before=_knobs_snapshot(base))

    applied = 0
    for cause in gap.causes:
        if applied >= max_moves:
            break
        if cause["lift"] < min_lift or cause["excess_misses_explained"] <= 0:
            continue
        move = ADVERSARIAL_MOVES.get(cause["key"])
        if move is None:
            continue
        # Scale the push by how strongly this cause discriminates misses.
        t = float(np.clip(intensity * min(cause["lift"] / 2.0, 1.0) + 0.25, 0.0, 1.0))
        move.apply(k, t)
        plan.moves.append({
            "cause_key": cause["key"], "cause_label": cause["label"],
            "knob": move.knob, "lift": cause["lift"],
            "share_of_missed": cause["share_of_missed"],
            "attribution": cause.get("attribution", 0.0),
            "intensity_applied": round(t, 3),
            "rationale": move.rationale,
        })
        applied += 1

    k.label = "ADVERSARIAL"
    plan.knobs_after = _knobs_snapshot(k)
    plan.target_segments = [s for s in gap.weakest_segments[:5]]
    return k, plan


# --------------------------------------------------------------------------
class AdversarialGenerator:
    """Generates attacks aimed at a specific detector's measured weaknesses."""

    def __init__(self, red_team: RedTeam):
        self.rt = red_team

    # ------------------------------------------------------------------
    def generate(
        self,
        gap: GapReport,
        n_scenarios: int,
        *,
        base_difficulty: str = "HARD",
        intensity: float = 0.85,
        focus_types: Optional[Sequence[str]] = None,
        concentrate_on_weakest: bool = True,
        stream: str = "adversarial",
        campaign: str = "",
    ) -> Tuple[AttackBatch, AdaptationPlan]:
        """Gap-directed generation (interpretable mode)."""
        knobs, plan = adapt_knobs(gap, base_difficulty, intensity)

        types = list(focus_types) if focus_types else None
        if types is None and concentrate_on_weakest and gap.weakest_segments:
            # Weight generation toward the families that are actually failing.
            weak = [s["attack_type"] for s in gap.weakest_segments
                    if s["recall"] < max(0.99, gap.recall + 0.02)]
            types = list(dict.fromkeys(weak)) or None
        if not types:
            types = list(C.ATTACK_TYPES)

        batch = self.rt.generate(
            n_scenarios=n_scenarios, attack_types=types,
            difficulty_mix={"ADVERSARIAL": 1.0},
            knob_overrides={"ADVERSARIAL": knobs},
            stream=stream, campaign=campaign or "adv_campaign")
        batch.request["adaptation_plan"] = plan.to_dict()
        batch.request["focus_types"] = types
        return batch, plan

    # ------------------------------------------------------------------
    def search(
        self,
        gap: GapReport,
        n_keep: int,
        score_fn: Callable[[AttackBatch], np.ndarray],
        *,
        base_difficulty: str = "HARD",
        rounds: int = 3,
        oversample: float = 3.0,
        intensity_schedule: Sequence[float] = (0.5, 0.8, 1.0),
        stream: str = "adv_search",
    ) -> Tuple[AttackBatch, AdaptationPlan, List[Dict]]:
        """Score-guided evasion search against the deployed detector.

        `score_fn(batch) -> per-scenario max detector score`. Scenarios with the
        lowest maximum score are the most evasive (no event in the sequence
        crossed the alerting threshold) and are retained.

        This is genuine black-box adversarial search: the attacker learns only
        from the detector's outputs, exactly as an attacker probing a live
        decision endpoint would.
        """
        history: List[Dict] = []
        kept_frames: List[AttackBatch] = []
        plan: Optional[AdaptationPlan] = None
        per_round = max(1, int(np.ceil(n_keep / max(1, rounds))))

        for r in range(rounds):
            intensity = float(intensity_schedule[min(r, len(intensity_schedule) - 1)])
            knobs, plan = adapt_knobs(gap, base_difficulty, intensity)
            n_cand = int(per_round * oversample)
            cand = self.rt.generate(
                n_scenarios=n_cand,
                attack_types=list(dict.fromkeys(
                    [s["attack_type"] for s in gap.weakest_segments])) or None,
                difficulty_mix={"ADVERSARIAL": 1.0},
                knob_overrides={"ADVERSARIAL": knobs},
                stream=f"{stream}:r{r}", campaign=f"adv_search_r{r}")
            if cand.events.empty:
                continue
            scores = score_fn(cand)                       # one score per scenario
            sc = cand.scenarios.copy()
            sc["evasion_score"] = scores
            keep_ids = set(sc.nsmallest(per_round, "evasion_score")["attack_id"])
            ev = cand.events[cand.events["attack_id"].isin(keep_ids)]
            kept = AttackBatch(
                events=ev.reset_index(drop=True),
                extra_customers=cand.extra_customers,
                extra_merchants=cand.extra_merchants,
                scenarios=sc[sc["attack_id"].isin(keep_ids)].reset_index(drop=True),
                request=dict(cand.request))
            kept_frames.append(kept)
            history.append({
                "round": r + 1, "intensity": intensity,
                "candidates": int(len(sc)), "kept": int(len(keep_ids)),
                "mean_score_all": round(float(np.mean(scores)), 6),
                "mean_score_kept": round(float(sc.nsmallest(per_round, "evasion_score")
                                               ["evasion_score"].mean()), 6),
            })

        if not kept_frames:
            empty = self.rt.generate(0)
            return empty, (plan or AdaptationPlan(base_difficulty, 0.0)), history

        def cat(attr: str, dedup: Optional[str] = None) -> pd.DataFrame:
            frames = [getattr(b, attr) for b in kept_frames]
            frames = [f for f in frames if f is not None and len(f) > 0]
            if not frames:
                return getattr(kept_frames[0], attr).copy()
            out = pd.concat(frames, ignore_index=True)
            return out.drop_duplicates(dedup) if dedup else out

        merged = AttackBatch(
            events=cat("events"),
            extra_customers=cat("extra_customers", "customer_id"),
            extra_merchants=cat("extra_merchants", "merchant_id"),
            scenarios=cat("scenarios"),
            request={"mode": "search", "rounds": rounds, "n_keep": n_keep,
                     "adaptation_plan": (plan.to_dict() if plan else {}),
                     "history": history})
        return merged, (plan or AdaptationPlan(base_difficulty, 0.0)), history


